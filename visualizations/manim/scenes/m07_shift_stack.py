"""M07: shift-and-stack over a velocity grid, the idea behind a Planet X search. CONCEPTUAL, SIMULATED."""

import numpy as np
from manim import (DOWN, LEFT, RIGHT, UP, BOLD, FadeIn, FadeOut, LaggedStart, Rectangle, Square,
                   VGroup, Transform, ReplacementTransform, SurroundingRectangle, Create)

import _path  # noqa: F401
from hviz.style import BLUE, GOLD, GREY, MUTED, ORANGE, TEXT, HScene, T, pixel_grid, seq_color

EVIDENCE = []
LABELS = ("CONCEPTUAL", "SIMULATED")
N_FRAMES, SIZE, SEED = 8, 15, 2026
TRUE_V = (1, 1)            # px per frame, the SIMULATED mover
MOVER_SNR = 2.2            # per frame: invisible alone, ~6 after stacking 8 frames
VGRID = range(-2, 3)       # trial velocities, px per frame


def simulate():
    """All SIMULATED: Gaussian noise, a few static stars, one faint mover."""
    rng = np.random.default_rng(SEED)
    yy, xx = np.mgrid[0:SIZE, 0:SIZE]
    static = np.zeros((SIZE, SIZE))
    for x, y, a in [(3, 11, 9.0), (11, 4, 6.0), (12, 12, 7.0)]:
        static += a * np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * 0.7 ** 2))
    x0, y0 = 3, 3
    frames = []
    for k in range(N_FRAMES):
        mx, my = x0 + TRUE_V[0] * k, y0 + TRUE_V[1] * k
        mover = MOVER_SNR * np.exp(-((xx - mx) ** 2 + (yy - my) ** 2) / (2 * 0.7 ** 2))
        frames.append(static + mover + rng.normal(0, 1, (SIZE, SIZE)))
    return frames, (x0, y0)


def stack(frames, v):
    # We shift each frame back along the trial velocity, then average; np.roll wraps
    # at the edges, which is fine for a sketch and keeps the noise statistics.
    return np.mean([np.roll(f, (-v[1] * k, -v[0] * k), axis=(0, 1)) for k, f in enumerate(frames)], axis=0)


def numbers():
    frames, start = simulate()
    # We remove the static sky first (median over frames), as a real search would;
    # otherwise bright stars dragged along a wrong velocity mimic a detection.
    template = np.median(frames, axis=0)
    diff = [f - template for f in frames]
    score = {}
    for vx in VGRID:
        for vy in VGRID:
            s = stack(diff, (vx, vy))
            # Score at the mover's start position, in units of the stacked noise.
            score[(vx, vy)] = float(s[start[1], start[0]] / (1 / np.sqrt(N_FRAMES)))
    best = max(score, key=score.get)
    return {"frames": frames, "diff": diff, "start": start, "score": score, "best": best, "true_v": TRUE_V,
            "best_snr": score[best]}


def norm(v, lo=-1.5, hi=4.0):
    return (min(max(v, lo), hi) - lo) / (hi - lo)


class M07ShiftStack(HScene):
    SCENE_ID = "M07"
    TITLE = "Planet X idea: shift-and-stack over trial velocities"
    LABELS = LABELS
    SOURCE = "SIMULATED noise, stars and mover generated by HIPPARCHUS · no archive data shown"

    def construct(self):
        n = numbers()
        frames = n["frames"]
        PX = 0.16
        single = pixel_grid(frames[0].tolist(), PX, seq_color, norm).move_to([-4.4, 0.85, 0])
        heads = [T("one exposure", 17, TEXT, weight=BOLD), T("stack, no shift", 17, TEXT, weight=BOLD),
                 T("static sky removed, shifted, stacked", 17, TEXT, weight=BOLD)]
        heads[0].next_to(single, UP, buff=0.12)
        sub0 = T(f"mover S/N {MOVER_SNR:g} per frame", 14, MUTED).next_to(single, DOWN, buff=0.1)
        self.play(FadeIn(single), FadeIn(heads[0]), FadeIn(sub0), run_time=0.6)
        # Flip through a few frames so the mover's motion is visible.
        for k in (2, 4, 6):
            self.play(Transform(single, pixel_grid(frames[k].tolist(), PX, seq_color, norm).move_to(single)), run_time=0.25)

        plain = pixel_grid(stack(frames, (0, 0)).tolist(), PX, seq_color, lambda v: norm(v * 2.0)).move_to([-0.6, 0.85, 0])
        heads[1].next_to(plain, UP, buff=0.12)
        sub1 = T("stars add up, the mover smears", 14, MUTED).next_to(plain, DOWN, buff=0.1)
        self.play(FadeIn(plain), FadeIn(heads[1]), FadeIn(sub1), run_time=0.7)

        # Velocity grid: scan trial velocities, colour = stacked S/N at the start position.
        cells = VGroup()
        smax = max(n["score"].values())
        for vy in reversed(list(VGRID)):
            for vx in VGRID:
                sc = n["score"][(vx, vy)]
                c = Square(0.36, stroke_color="#0A1630", stroke_width=1.5, fill_color=seq_color(max(sc, 0) / smax),
                           fill_opacity=1)
                c.v = (vx, vy)
                cells.add(c)
        cells.arrange_in_grid(rows=len(VGRID), cols=len(VGRID), buff=0.03).move_to([-0.6, -1.75, 0])
        vlab = T("trial velocities: vx → , vy ↑ (px per frame)", 14, MUTED).next_to(cells, LEFT, buff=0.25)
        self.play(LaggedStart(*[FadeIn(c) for c in cells], lag_ratio=0.04), FadeIn(vlab), run_time=1.0)
        best_cell = next(c for c in cells if c.v == n["best"])
        box = SurroundingRectangle(best_cell, color=GOLD, buff=0.03, stroke_width=4)

        shifted = pixel_grid(stack(n["diff"], n["best"]).tolist(), PX, seq_color, lambda v: norm(v * 2.0)).move_to([3.2, 0.85, 0])
        heads[2].next_to(shifted, UP, buff=0.12)
        sx, sy = n["start"]
        ring = Square(PX * 2.4, stroke_color=GOLD, stroke_width=3).move_to(shifted[sy * SIZE + sx])
        sub2 = T(f'v = {n["best"]}: mover adds up, S/N ≈ {n["best_snr"]:.1f}', 14, GOLD).next_to(shifted, DOWN, buff=0.1)
        self.play(Create(box), FadeIn(shifted), FadeIn(heads[2]), run_time=0.8)
        self.play(Create(ring), FadeIn(sub2), run_time=0.5)

        notes = VGroup(T("Every pixel here is SIMULATED.", 17, GOLD, weight=BOLD),
                       T("A real search needs many more epochs, motion", 15, TEXT),
                       T("curvature and a false-alarm budget.", 15, TEXT),
                       T("HIPPARCHUS has not found Planet X.", 17, TEXT, weight=BOLD)).arrange(DOWN, aligned_edge=LEFT, buff=0.1)
        notes.move_to([3.6, -2.0, 0])
        self.play(FadeIn(notes), run_time=0.6)
        self.wait(1.4)
